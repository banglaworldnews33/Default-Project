export const productBySlug = (slug: string): Product | undefined =>
  products.find((p) => p.slug === slug)

export const productById = (id: string): Product | undefined =>
  products.find((p) => p.id === id)

/** Low-stock threshold used across UI and admin (configurable in Settings later). */
export const LOW_STOCK_THRESHOLD = 10

export const stockStatusOf = (product: Product): 'in-stock' | 'low-stock' | 'out-of-stock' => {
  if (product.stock <= 0) return 'out-of-stock'
  if (product.stock <= LOW_STOCK_THRESHOLD) return 'low-stock'
  return 'in-stock'
}
